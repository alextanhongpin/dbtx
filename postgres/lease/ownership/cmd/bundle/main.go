// Command bundle copies standalone lease SQL into the retry source bundle.
// The retry generator distributes the combined SQL to its consumers.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
)

func main() {
	root := flag.String("root", "../../..", "repository root")
	check := flag.Bool("check", false, "verify without writing")
	flag.Parse()
	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(root string, check bool) error {
	common, err := os.ReadFile(filepath.Join(root, "postgres", "lease", "ownership", "schema.sql"))
	if err != nil {
		return err
	}
	common = append([]byte("-- Code generated by postgres/lease/ownership/cmd/bundle; DO NOT EDIT.\n"), common...)
	return output(filepath.Join(root, "postgres", "retry", "shared_ownership.sql"), common, check)
}

func output(path string, content []byte, check bool) error {
	if check {
		actual, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(actual, content) {
			return fmt.Errorf("stale bundle %s", path)
		}
		return nil
	}
	return os.WriteFile(path, content, 0o644)
}
