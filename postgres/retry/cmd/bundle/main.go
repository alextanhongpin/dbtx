// Command bundle distributes the shared SQL to independently released modules.
// Run through go generate in postgres/retry; -check verifies generated bundles.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
)

func main() {
	check := flag.Bool("check", false, "verify bundles without writing")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(check bool) error {
	source, err := os.ReadFile("schema.sql")
	if err != nil {
		return err
	}
	common, err := os.ReadFile("shared_ownership.sql")
	if err != nil {
		return err
	}
	source = append(common, source...)
	bundle := append([]byte("-- Code generated by postgres/retry/cmd/bundle; DO NOT EDIT.\n"), source...)
	for _, module := range []string{"idempotent", "inbox", "jobs", "outbox"} {
		path := filepath.Join("..", module, "repository", "shared_retry.sql")
		if check {
			actual, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if !bytes.Equal(actual, bundle) {
				return fmt.Errorf("%s is stale; run go generate ./postgres/retry", path)
			}
		} else if err := os.WriteFile(path, bundle, 0o644); err != nil {
			return err
		}
	}
	return nil
}
